package main

// Generates bitejson/fastparse.go from bitejson/refparser.go so the grammar and
// diagnostics are identical by construction; only the scanning primitives are
// swapped for mask-accelerated ones.

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	src, err := os.ReadFile("bitejson/refparser.go")
	if err != nil {
		panic(err)
	}
	s := string(src)

	// Split off the shared token/lineScan definitions; the fast file reuses
	// them from refparser.go.
	keepStart := strings.Index(s, "// refParser validates one JSON line")
	if keepStart < 0 {
		panic("marker not found")
	}
	head := s[:keepStart]
	body := s[keepStart:]

	// Shared helpers (quoteChar..isDigit, setEOF semantics) stay in refparser.go;
	// drop them from the body by locating the parser type.
	body = strings.ReplaceAll(body, "refParser", "parser")
	body = strings.ReplaceAll(body, "*parser", "*parser")

	// Replace the per-byte string scan with the mask-driven one.
	oldSkipStart := strings.Index(body, "func (p *parser) skipString(i int) (int, bool) {")
	oldSkipEnd := strings.Index(body, "\n}\n", oldSkipStart)
	if oldSkipStart < 0 || oldSkipEnd < 0 {
		panic("skipString not found")
	}
	body = body[:oldSkipStart] + fastSkipString + body[oldSkipEnd+3:]

	// Replace the scalar-number scan with the mask-driven one.
	oldNumStart := strings.Index(body, "func (p *parser) number(i int) (int, bool) {")
	oldNumEnd := strings.Index(body, "\n}\n", oldNumStart)
	if oldNumStart < 0 || oldNumEnd < 0 {
		panic("number not found")
	}
	body = body[:oldNumStart] + fastNumber + body[oldNumEnd+3:]

	// Drop the unused numAt helper.
	if a := strings.Index(body, "func (p *parser) numAt("); a >= 0 {
		if b := strings.Index(body, "\n}\n", a); b >= 0 {
			body = body[:a] + body[b+3:]
		}
	}

	// Replace skipSpace with the mask-driven one.
	oldSP := strings.Index(body, "func (p *parser) skipSpace(i int) int {")
	oldSPEnd := strings.Index(body, "\n}\n", oldSP)
	if oldSP < 0 || oldSPEnd < 0 {
		panic("skipSpace not found")
	}
	body = body[:oldSP] + fastSkipSpace + body[oldSPEnd+3:]

	header := `// Code generated by cmd/gen from refparser.go; DO NOT EDIT.

package bitejson
`
	var sb strings.Builder
	sb.WriteString(header)
	sb.WriteString("\n// The line parser below shares its grammar and diagnostics with the\n")
	sb.WriteString("// byte-at-a-time reference parser used to validate it; the primitives that\n")
	sb.WriteString("// scan string bodies, numbers and whitespace use the precomputed masks.\n")
	sb.WriteString(body)
	out := sb.String()
	if err := os.WriteFile("bitejson/fastparse.go", []byte(out), 0o644); err != nil {
		panic(err)
	}
	_ = head
	fmt.Println("wrote bitejson/fastparse.go")
}

const fastSkipString = `func (p *parser) skipString(i int) (int, bool) {
	ls := p.ls
	end := int(ls.closeQAt(i))
	if end < 0 {
		p.setEOF("unexpected end of JSON input")
		return len(ls.data), false
	}
	// The masks prove the string is terminated and every escape is one of the
	// legal forms; only \u escapes need per-character checking for hex digits.
	if ls.bslash != 0 {
		j := i + 1
		// Iterate only over backslashes before the closing quote.
		m := ls.bslash >> uint(j&63)
		for m != 0 {
			rel := trailing(m)
			bj := j + rel
			if bj >= end {
				break
			}
			if ls.data[bj+1] == 'u' {
				for k := 2; k < 6; k++ {
					if bj+k >= len(ls.data) {
						p.setEOF(` + "`" + `invalid character ' ' in \u hexadecimal character escape` + "`" + `)
						return bj, false
					}
					if !isHex(ls.data[bj+k]) {
						p.setErr(ErrSyntax, bj+k, syntaxMsg(ls.data[bj+k], ` + "`" + `in \u hexadecimal character escape` + "`" + `))
						return bj, false
					}
				}
			}
			m = lowClear(m)
		}
	}
	return end + 1, true
}

// closeQAt returns the offset of the first closing quote at or after i, or -1.
func (ls *lineScan) closeQAt(i int) int {
	m := ls.closeQ >> uint(i&63)
	if m == 0 {
		return -1
	}
	return i + trailing(m)
}
`

const fastNumber = `func (p *parser) number(i int) (int, bool) {
	ls := p.ls
	j := i
	if ls.at(j) == '-' {
		j++
	}
	switch {
	case ls.at(j) == '0':
		j++
	case '1' <= ls.at(j) && ls.at(j) <= '9':
		for isDigit(ls.at(j)) {
			j++
		}
	default:
		if j >= len(ls.data) {
			p.setEOF("invalid character ' ' in numeric literal")
		} else {
			p.setErr(ErrSyntax, j, syntaxMsg(ls.data[j], "in numeric literal"))
		}
		return j, false
	}
	if ls.at(j) == '.' {
		j++
		if !isDigit(ls.at(j)) {
			if j >= len(ls.data) {
				p.setEOF("invalid character ' ' after decimal point in numeric literal")
			} else {
				p.setErr(ErrSyntax, j, syntaxMsg(ls.data[j], "after decimal point in numeric literal"))
			}
			return j, false
		}
		for isDigit(ls.at(j)) {
			j++
		}
	}
	if c := ls.at(j); c == 'e' || c == 'E' {
		j++
		if c := ls.at(j); c == '+' || c == '-' {
			j++
		}
		if !isDigit(ls.at(j)) {
			if j >= len(ls.data) {
				p.setEOF("invalid character ' ' in exponent of numeric literal")
			} else {
				p.setErr(ErrSyntax, j, syntaxMsg(ls.data[j], "in exponent of numeric literal"))
			}
			return j, false
		}
		for isDigit(ls.at(j)) {
			j++
		}
	}
	return j, true
}
`

const fastSkipSpace = `func (p *parser) skipSpace(i int) int {
	ls := p.ls
	for i < len(ls.data) {
		m := (^ls.ws) >> uint(i&63)
		if m&1 == 0 {
			// byte i is whitespace; skip the whole run.
			i += trailing(m)
			continue
		}
		return i
	}
	return i
}
`
